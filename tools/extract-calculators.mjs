#!/usr/bin/env node
// extract-calculators.mjs — generate src/core/calculators/calculators.mjs from
// main:flowchart.html. (Phase 7, calculator kernel.)
//
// v1's calculators are named functions (calcCompound, …) that read numeric inputs
// via $val(id, default) / document.getElementById(id).value and write their result
// into document.getElementById('<id>-result').innerHTML. The compute is pure; only
// the DOM read/write and an optional chart-draw side-effect couple it to the page.
// This tool lifts the calc fns + their helpers ($val/fmtMoney/fmtMoneyFull) VERBATIM
// and hosts them under a minimal DOM-input shim, yielding a pure, self-contained
// runCalculator(name, inputs) -> { id, html }. Chart side-effects are stubbed. Zero
// math retyping → faithful by construction; proven by tools/verify-calculators.mjs.
//
// Scope (this increment): the closed-form math calculators. The chart-drawing
// simulators (calcSequence / calcAssetLocation / calcHistoricalCycles) and the
// spending/portfolio/zeitgeist calcs are deferred to later increments.

import { writeFileSync, readFileSync, mkdirSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
let src;
try { src = execSync('git show main:flowchart.html', { cwd: ROOT, maxBuffer: 64 * 1024 * 1024 }).toString('utf8'); }
catch { src = readFileSync(join(ROOT, 'flowchart.html'), 'utf8'); }

// balanced-brace function extractor (quote/comment-aware) — same as extract-prose.
function skipStr(s, q) { const quote = s[q]; let i = q + 1; while (i < s.length) { if (s[i] === '\\') { i += 2; continue; } if (s[i] === quote) return i + 1; i++; } return i; }
function balancedFrom(s, start) {
  let depth = 0, i = start;
  for (; i < s.length; i++) {
    const c = s[i];
    if (c === '"' || c === "'" || c === '`') { i = skipStr(s, i) - 1; continue; }
    if (c === '/' && s[i + 1] === '/') { i = s.indexOf('\n', i); if (i === -1) { i = s.length; break; } continue; }
    if (c === '/' && s[i + 1] === '*') { i = s.indexOf('*/', i) + 1; continue; }
    if (c === '{') depth++;
    else if (c === '}') { depth--; if (depth === 0) return i + 1; }
  }
  return i;
}
function pullFn(name) {
  const at = src.indexOf('function ' + name + '(');
  if (at === -1) throw new Error('not found: ' + name);
  const brace = src.indexOf('{', src.indexOf(')', at));
  return src.slice(at, balancedFrom(src, brace));
}

// Pull the min/max/value/step attributes of the calculator inputs so $val's
// clamp-to-attribute behavior reproduces v1 exactly (and the UI can seed defaults).
function attrOf(tag, name) { const m = tag.match(new RegExp(`\\b${name}="([^"]*)"`)); return m ? m[1] : null; }
function parseInputs() {
  const attrs = {};
  const re = /<(?:input|select)\b[^>]*\bid="((?:ci|r72|sr|rn|muni)-[^"]*)"[^>]*>/g;
  let m;
  while ((m = re.exec(src))) {
    const tag = m[0], id = m[1];
    attrs[id] = {};
    for (const a of ['min', 'max', 'value', 'step']) { const v = attrOf(tag, a); if (v != null) attrs[id][a] = v; }
  }
  return attrs;
}

const HELPERS = ['$val', 'fmtMoney', 'fmtMoneyFull'];
// name -> [v1 fn, result element id]
const CALCS = [
  ['compound', 'calcCompound', 'ci-result'],
  ['rule72', 'calcRule72', 'r72-result'],
  ['savingsRate', 'calcSavingsRate', 'sr-result'],
  ['realNominal', 'calcRealNominal', 'rn-result'],
  ['muniTEY', 'calcMuniTEY', 'muni-result'],
];

// Emit verbatim — do NOT re-indent: these functions contain multi-line template
// literals whose internal whitespace IS part of the output HTML (must stay byte-exact).
const helperSrc = HELPERS.map((n) => pullFn(n)).join('\n');
const calcSrc = CALCS.map(([, fn]) => pullFn(fn)).join('\n');
const dispatch = CALCS.map(([key, fn]) => `    ${key}: ${fn}`).join(',\n');
const resultIds = CALCS.map(([key, , id]) => `    ${key}: '${id}'`).join(',\n');

const out = `// calculators.mjs — AUTO-GENERATED by tools/extract-calculators.mjs from
// main:flowchart.html. Verbatim v1 calculator compute fns under a DOM-input shim.
// DO NOT HAND-EDIT — regenerate when v1 calcs change. Faithful-by-construction;
// byte-exact parity proven by tools/verify-calculators.mjs (v1-live vs v2).
/* eslint-disable */

export const CALCULATORS = ${JSON.stringify(CALCS.map(([k, , id]) => ({ name: k, resultId: id })))};

// Input min/max/value/step from v1's calculator markup (drives $val clamping + UI defaults).
export const INPUT_ATTRS = ${JSON.stringify(parseInputs())};

/**
 * Run a calculator by name with a map of input-id -> raw value (string|number).
 * Returns { id, html } — the result element id and the HTML v1 would have written.
 * Pure: no real DOM, no chart side-effects (stubbed). Unknown ids fall back to the
 * calc's own defaults (v1 $val semantics), and clamp to INPUT_ATTRS min/max.
 */
export function runCalculator(name, inputs) {
  const __in = inputs || {};
  const __out = {};
  const __el = (id) => ({
    get value() { return __in[id]; },
    set innerHTML(h) { __out[id] = h; },
    get innerHTML() { return __out[id] || ''; },
    getAttribute(a) { return (INPUT_ATTRS[id] && INPUT_ATTRS[id][a] != null) ? INPUT_ATTRS[id][a] : null; },
    get tagName() { const v = __in[id]; return (v != null && isNaN(parseFloat(v))) ? 'SELECT' : 'INPUT'; },
  });
  const document = { getElementById: __el };
  const renderCompoundChart = () => {}; // chart side-effect — not part of the pure result
${helperSrc}
${calcSrc}
  const __dispatch = {
${dispatch}
  };
  const __resultId = {
${resultIds}
  };
  const fn = __dispatch[name];
  if (!fn) throw new Error('unknown calculator: ' + name);
  fn();
  const id = __resultId[name];
  return { id, html: __out[id] || '' };
}
`;

mkdirSync(join(ROOT, 'src', 'core', 'calculators'), { recursive: true });
writeFileSync(join(ROOT, 'src', 'core', 'calculators', 'calculators.mjs'), out);
console.log(`wrote src/core/calculators/calculators.mjs (${CALCS.length} calculators: ${CALCS.map((c) => c[0]).join(', ')})`);
